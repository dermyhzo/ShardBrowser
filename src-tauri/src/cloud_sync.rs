    fn copy_tree_skips_caches_and_mirrors() {
        let base = std::env::temp_dir().join(format!("shardx-sync-test-{}", std::process::id()));
        let (src, dst) = (base.join("src"), base.join("dst"));
        fs::create_dir_all(src.join("Default/Cache")).unwrap();
        fs::write(src.join("Default/Cookies"), "c").unwrap();
        fs::write(src.join("Default/Cache/x"), "junk").unwrap();
        fs::write(src.join("SingletonLock"), "").unwrap();
        fs::create_dir_all(dst.join("stale")).unwrap();

        assert_eq!(copy_tree(&src, &dst, true).unwrap(), 1);
        assert_eq!(fs::read_to_string(dst.join("Default/Cookies")).unwrap(), "c");
        assert!(!dst.join("Default/Cache").exists());
        assert!(!dst.join("SingletonLock").exists());
        assert!(!dst.join("stale").exists());
        // Unchanged files are not copied again.
        assert_eq!(copy_tree(&src, &dst, true).unwrap(), 0);
        let _ = fs::remove_dir_all(&base);
    }

